"""Промпт-шаблоны генератора диалогов (стадия 1, методичка §9.2).

Вшито: длина 6-14 с естественной эскалацией; правила онсета v1.2; плейсхолдеры
для чувствительного; ЖЁСТКОЕ разделение сторон (role atk/tgt + стабильный speaker);
контракт вывода — только JSON с черновыми метками.
"""
import json

from .scenarios import SCENARIOS

PLACEHOLDERS = "(URL), (CARD), (CODE), (AMOUNT), (NAME), (NUM), (APP), (BRAND)"

LANG_NAMES = {"ru": "русском", "en": "английском", "zh": "китайском (упрощённый)"}

SYSTEM_PROMPT = (
    "Ты генерируешь синтетические диалоги для исследовательского корпуса детекции скама "
    "(обучение защитных моделей ранней детекции обмана; разметка по замороженному "
    "гайдлайну v1.2). Правила безопасности:\n"
    f"- всё чувствительное — ТОЛЬКО плейсхолдеры: {PLACEHOLDERS}; никаких настоящих ссылок, "
    "номеров карт, кодов, телефонов и реальных брендов;\n"
    "- обман показывай на уровне сюжета, без работающих вредоносных инструкций;\n"
    "- никаких несовершеннолетних в романтических/интимных контекстах.\n"
    "Отвечай ТОЛЬКО валидным JSON: без пояснений, без markdown-ограждений."
)

# Правила онсета — из annotation_guidelines v1 §4 + Правила 1-2 v1.1 (заморожено в v1.2).
_ONSET_RULES = (
    "Правила онсета (гайдлайн v1.2) для черновой метки:\n"
    "- онсет = номер ПЕРВОЙ реплики atk, где обман ПРИСУТСТВУЕТ в тексте: (a) ложная/"
    "непроверяемая легенда или личность как факт; (b) фабрикация срочности/угрозы/выгоды; "
    "(c) первое побуждение к небезопасному действию; (d) запрос конфиденциальных данных;\n"
    "- ложная личность, заявленная как факт («это служба безопасности банка»), — УЖЕ онсет, "
    "до всякой просьбы (Правило 1);\n"
    "- медленный заход (романтика/дружба): онсет = первая непроверяемая легенда как факт, "
    "НЕ эмоция в начале и НЕ просьба денег в конце (Правило 2);\n"
    "- приветствие, small talk и эмоции сами по себе — НЕ онсет."
)

_SIDES_RULES = (
    "Стороны (ЖЁСТКО, ровно две, третьих участников нет):\n"
    "- каждая реплика имеет role: \"atk\" (инициатор{deceit}) или \"tgt\" (цель/собеседник), "
    "и speaker — короткую человекочитаемую стабильную метку стороны на языке диалога "
    "(роль сценария вроде «Банк»/«Клиент», имя, или «Участник 1»=atk / «Участник 2»=tgt);\n"
    "- один speaker = одна role ВЕСЬ диалог; кто есть кто, НЕ меняется по ходу;\n"
    "- чередование естественное, как в мессенджере: сторона может писать 2+ реплики подряд, "
    "но каждая реплика однозначно принадлежит одной стороне."
)

_JSON_CONTRACT = (
    "Верни ТОЛЬКО такой JSON:\n"
    '{{"turns": [{{"i": 1, "role": "atk", "speaker": "...", "text": "..."}}, ...],\n'
    ' "draft_labels": {{"is_scam": {is_scam}, "subtypes": {subtypes_hint}, '
    '"onset": {onset_hint}}}}}'
)

_SCAM_TEMPLATE = """Сгенерируй реалистичный диалог в мессенджере НАТИВНО на {lang_name} языке \
(имена, реалии, стиль — не перевод).

Сценарий (скам): {setup}.
- atk: {atk_role};
- tgt: {tgt_role}.

{sides}

Структура (жёстко):
- РОВНО {n_turns} реплик, i = 1..{n_turns};
- длинный, многоходовый и реалистичный: заход -> доверие -> первая обманная улика -> \
эскалация (доверие -> срочность -> эмоции/дожим); НЕ one-shot приманка;
{onset_placement}
- раньше реплики {onset_cand} обманных улик НЕ вставлять; после — естественная эскалация;
- цель tgt — вести себя правдоподобно (уточнять, сомневаться или поддаваться), без карикатуры.

{onset_rules}

Черновые метки (draft_labels), поставь сам по правилам v1.2:
- is_scam = 1;
- subtypes ⊆ ["phishing_link", "money_request", "other"]: phishing_link — ведут по ссылке \
за данными/оплатой; money_request — просят перевод/оплату/комиссию; other — обман через \
роль или сценарий; если деньги просят ЧЕРЕЗ роль — ставь И money_request, И other;
- onset — номер реплики первой обманной улики (перепроверь по правилам выше, это может \
быть не {onset_cand}, если улика фактически появилась в другой реплике).

{json_contract}"""

_BENIGN_TEMPLATE = """Сгенерируй реалистичный диалог в мессенджере НАТИВНО на {lang_name} языке \
(имена, реалии, стиль — не перевод).

Сценарий (BENIGN, обмана нет): {setup}.
- atk: {atk_role} (здесь \"atk\" — просто сторона-инициатор диалога, БЕЗ обмана);
- tgt: {tgt_role}.

{sides}

Структура (жёстко):
- РОВНО {n_turns} реплик, i = 1..{n_turns};
- длинный, многоходовый, бытовой и реалистичный — не рекламный однострочник;
- {onset_rule};{hard_neg_clause}
- никакого побуждения к небезопасному действию в пользу инициатора: не просить коды из СМС, \
полные данные карты, установку ПО, перевод «на безопасный счёт».

Черновые метки (draft_labels): is_scam = 0, subtypes = [], onset = null — всегда \
(инвариант: benign -> онсет пуст).

{json_contract}"""

_HARD_NEG_CLAUSE = (
    "\n- это HARD NEGATIVE: в диалоге ЕСТЬ деньги/ссылка/срочность или тревожный тон, "
    "но всё ПРАВДИВО — без ложной легенды (это главный источник ложных тревог, "
    "он нужен корпусу);"
)


def _onset_placement(onset_cand, onset_rule):
    if onset_cand > 1:
        return (
            f"- реплики 1..{onset_cand - 1} — БЕЗ обмана: нейтральный правдоподобный заход "
            f"без критериев (a)-(d);\n"
            f"- реплика {onset_cand} (сторона atk) — ПЕРВАЯ обманная улика: {onset_rule};"
        )
    return f"- ПЕРВАЯ же реплика (сторона atk) уже содержит обманную улику: {onset_rule};"


def build_prompt(skel):
    """(system, user) для скелета; сценарные правила берутся из таксономии."""
    sc = SCENARIOS[skel.scenario_id]
    lang_name = LANG_NAMES.get(skel.lang, skel.lang)
    if sc.is_scam:
        sides = _SIDES_RULES.format(deceit=" обмана")
        user = _SCAM_TEMPLATE.format(
            lang_name=lang_name, setup=sc.setup,
            atk_role=sc.roles[0], tgt_role=sc.roles[1], sides=sides,
            n_turns=skel.n_turns, onset_cand=skel.onset_cand,
            onset_placement=_onset_placement(skel.onset_cand, sc.onset_rule),
            onset_rules=_ONSET_RULES,
            json_contract=_JSON_CONTRACT.format(
                is_scam=1, subtypes_hint=json.dumps(list(sc.subtypes)), onset_hint="N"),
        )
    else:
        sides = _SIDES_RULES.format(deceit="")
        user = _BENIGN_TEMPLATE.format(
            lang_name=lang_name, setup=sc.setup,
            atk_role=sc.roles[0], tgt_role=sc.roles[1], sides=sides,
            n_turns=skel.n_turns, onset_rule=sc.onset_rule,
            hard_neg_clause=_HARD_NEG_CLAUSE if sc.hard_negative else "",
            json_contract=_JSON_CONTRACT.format(
                is_scam=0, subtypes_hint=[], onset_hint="null"),
        )
    return SYSTEM_PROMPT, user
