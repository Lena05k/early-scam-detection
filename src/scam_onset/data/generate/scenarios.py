"""Таксономия сценариев генерации (CLAUDE.md «Решение по корпусу», методичка §9.1).

Каждый сценарий фиксирует метки уровня диалога (is_scam, подтипы — мультилейбл),
логику онсета по замороженному гайдлайну v1.2 (памятка v1.2 + Правила 1-2 из v1.1)
и benign-двойника для hard-negative mining (методичка §9.3, режим 4).

Онсет сценария — ПРАВИЛО для генератора и черновой метки (t*_cand), не золото:
t*_cand -> t*_gold только после человеческой верификации (методичка §9.2, стадия 2).
"""
from dataclasses import dataclass

# Инвариант CLAUDE.md №1: подтипы — фиксированный мультилейбл-набор.
SUBTYPES = ("phishing_link", "money_request", "other")


@dataclass(frozen=True)
class Scenario:
    id: str
    is_scam: int                      # 0/1 — метка уровня диалога
    subtypes: tuple                   # ожидаемые подтипы (у benign — пусто)
    roles: tuple                      # (описание atk-стороны, описание tgt-стороны) для промпта
    setup: str                        # ситуация сценария для промпта
    onset_rule: str                   # логика первой обманной улики по v1.2 (у benign — «обмана нет»)
    onset_window: tuple | None        # (lo, hi) — диапазон кандидата t*_cand; None у benign
    twin: str | None = None           # id benign-двойника (hard-negative mining)
    hard_negative: int = 0            # только для benign: деньги/ссылка/срочность без обмана
    other_note: str = ""              # заметка для sub_other (конвенция make_synth)


